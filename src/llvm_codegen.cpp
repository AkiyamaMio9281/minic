#include "llvm_codegen.hpp"

#include <cstddef>
#include <ostream>
#include <string>
#include <vector>

namespace {

// Indices into TRAP_MESSAGES in runtime/minic_rt.c. The order is a
// contract between the two files.
enum Trap {
    TrapOverflow = 0,
    TrapDivisionByZero = 1,
    TrapRemainderByZero = 2,
    TrapDivisionOverflow = 3,
    TrapNegationOverflow = 4,
};

// MiniC cannot write this as a literal, but the checks have to compare
// against it.
const char* const INT_MIN_TEXT = "-2147483648";

// User functions are prefixed so that MiniC's main does not collide with
// the C runtime's, nor any MiniC name with printf and friends.
std::string mangle(const std::string& name) {
    return "@mc_" + name;
}

class Emitter {
public:
    Emitter(const Program& program, std::ostream& out)
        : program_(program), out_(out) {}

    void run() {
        out_ << "; Generated by minic --emit-llvm\n\n";
        declarations();
        functionNameConstants();

        for (const Function& function : program_.functions) {
            emitFunction(function);
        }
    }

private:
    // -----------------------------------------------------------------
    // Module level
    // -----------------------------------------------------------------

    void declarations() {
        out_ << "declare void @minic_print(i32)\n"
             << "declare void @minic_trap(i32, i32)\n"
             << "declare void @minic_trap_no_return(ptr, i32)\n"
             << "declare {i32, i1} @llvm.sadd.with.overflow.i32(i32, i32)\n"
             << "declare {i32, i1} @llvm.ssub.with.overflow.i32(i32, i32)\n"
             << "declare {i32, i1} @llvm.smul.with.overflow.i32(i32, i32)\n\n";
    }

    // Only the functions that can fall off their end need a name at
    // runtime: void functions return instead, and main returns zero.
    void functionNameConstants() {
        bool wroteAny = false;

        for (const Function& function : program_.functions) {
            if (!needsNoReturnTrap(function)) {
                continue;
            }

            const std::size_t size = function.name.size() + 1;
            out_ << nameConstant(function) << " = private unnamed_addr constant ["
                 << size << " x i8] c\"" << function.name << "\\00\"\n";
            wroteAny = true;
        }

        if (wroteAny) {
            out_ << "\n";
        }
    }

    static bool needsNoReturnTrap(const Function& function) {
        return !function.returnsVoid && function.name != "main";
    }

    static std::string nameConstant(const Function& function) {
        return "@.fn." + function.name;
    }

    // -----------------------------------------------------------------
    // Emission helpers
    // -----------------------------------------------------------------

    std::string freshValue() {
        return "%t" + std::to_string(nextId_++);
    }

    std::string freshLabel(const char* hint) {
        return std::string(hint) + "." + std::to_string(nextId_++);
    }

    void line(const std::string& text) {
        out_ << "  " << text << "\n";
    }

    void startBlock(const std::string& label) {
        out_ << label << ":\n";
        block_ = label;
        terminated_ = false;
    }

    void terminate(const std::string& text) {
        line(text);
        terminated_ = true;
    }

    // A statement after a return, or after an if whose branches all
    // return, has nowhere to go. LLVM rejects instructions following a
    // terminator, so such code goes into a fresh block that simply has no
    // predecessors.
    void ensureOpenBlock() {
        if (terminated_) {
            startBlock(freshLabel("dead"));
        }
    }

    // -----------------------------------------------------------------
    // Functions
    // -----------------------------------------------------------------

    void emitFunction(const Function& function) {
        nextId_ = 0;

        out_ << "define " << (function.returnsVoid ? "void " : "i32 ")
             << mangle(function.name) << "(";

        for (std::size_t i = 0; i < function.params.size(); ++i) {
            out_ << (i > 0 ? ", " : "") << "i32 %p" << i;
        }

        out_ << ") {\n";
        startBlock("entry");

        // One slot per local, parameters included, exactly as semantic
        // analysis numbered them. Promotion to SSA is left to the
        // optimizer rather than done here.
        for (int slot = 0; slot < function.localCount; ++slot) {
            line(slotPointer(slot) + " = alloca i32");
        }

        for (std::size_t i = 0; i < function.params.size(); ++i) {
            line("store i32 %p" + std::to_string(i) + ", ptr " +
                 slotPointer(static_cast<int>(i)));
        }

        emitStmt(*function.body);
        emitEpilogue(function);

        out_ << "}\n\n";
    }

    // Reached only when control runs off the end of the body.
    void emitEpilogue(const Function& function) {
        if (terminated_) {
            return;
        }

        if (function.returnsVoid) {
            terminate("ret void");
            return;
        }

        // main returning nothing is defined to return zero, matching C and
        // matching the VM. Any other int function is a runtime error, and
        // the VM blames the line the function opened on.
        if (function.name == "main") {
            terminate("ret i32 0");
            return;
        }

        line("call void @minic_trap_no_return(ptr " + nameConstant(function) +
             ", i32 " + std::to_string(function.line) + ")");
        terminate("unreachable");
    }

    static std::string slotPointer(int slot) {
        return "%s" + std::to_string(slot);
    }

    // -----------------------------------------------------------------
    // Statements
    // -----------------------------------------------------------------

    void emitStmt(const Stmt& statement) {
        ensureOpenBlock();

        switch (statement.kind) {
            case Stmt::Kind::VarDecl: {
                const auto& decl = static_cast<const VarDecl&>(statement);

                // Slots are reused between sibling blocks, so a
                // declaration without an initializer stores an explicit
                // zero rather than trusting whatever the slot holds. The
                // bytecode backend does the same.
                const std::string value =
                    decl.init ? emitExpr(*decl.init) : std::string("0");

                line("store i32 " + value + ", ptr " + slotPointer(decl.slot));
                return;
            }

            case Stmt::Kind::ExprStmt: {
                const auto& exprStmt = static_cast<const ExprStmt&>(statement);

                if (exprStmt.expr) {
                    // Whatever it produces is simply not used. There is no
                    // operand stack to clean up.
                    emitExpr(*exprStmt.expr);
                }

                return;
            }

            case Stmt::Kind::If:
                emitIf(static_cast<const If&>(statement));
                return;

            case Stmt::Kind::While:
                emitWhile(static_cast<const While&>(statement));
                return;

            case Stmt::Kind::Return: {
                const auto& ret = static_cast<const Return&>(statement);

                if (ret.value) {
                    const std::string value = emitExpr(*ret.value);
                    terminate("ret i32 " + value);
                } else {
                    terminate("ret void");
                }

                return;
            }

            case Stmt::Kind::Block: {
                const auto& block = static_cast<const Block&>(statement);

                for (const StmtPtr& item : block.items) {
                    emitStmt(*item);
                }

                return;
            }
        }
    }

    void emitIf(const If& statement) {
        const std::string thenLabel = freshLabel("then");
        const std::string elseLabel = freshLabel("else");
        const std::string endLabel = freshLabel("endif");

        const std::string condition = emitTruth(*statement.cond);
        terminate("br i1 " + condition + ", label %" + thenLabel + ", label %" +
                  (statement.elseBranch ? elseLabel : endLabel));

        startBlock(thenLabel);
        emitStmt(*statement.thenBranch);

        if (!terminated_) {
            terminate("br label %" + endLabel);
        }

        if (statement.elseBranch) {
            startBlock(elseLabel);
            emitStmt(*statement.elseBranch);

            if (!terminated_) {
                terminate("br label %" + endLabel);
            }
        }

        // If both arms returned, this block has no predecessors. That is
        // legal, and the epilogue or a later statement terminates it.
        startBlock(endLabel);
    }

    void emitWhile(const While& statement) {
        const std::string condLabel = freshLabel("cond");
        const std::string bodyLabel = freshLabel("body");
        const std::string endLabel = freshLabel("endwhile");

        terminate("br label %" + condLabel);

        startBlock(condLabel);
        const std::string condition = emitTruth(*statement.cond);
        terminate("br i1 " + condition + ", label %" + bodyLabel + ", label %" +
                  endLabel);

        startBlock(bodyLabel);
        emitStmt(*statement.body);

        if (!terminated_) {
            terminate("br label %" + condLabel);
        }

        startBlock(endLabel);
    }

    // -----------------------------------------------------------------
    // Expressions
    // -----------------------------------------------------------------

    // Returns an operand usable wherever an i32 is expected, which is
    // either a literal or a register.
    std::string emitExpr(const Expr& expression) {
        switch (expression.kind) {
            case Expr::Kind::IntLiteral:
                return std::to_string(
                    static_cast<const IntLiteral&>(expression).value);

            case Expr::Kind::Variable: {
                const auto& variable = static_cast<const Variable&>(expression);
                const std::string result = freshValue();
                line(result + " = load i32, ptr " + slotPointer(variable.slot));
                return result;
            }

            case Expr::Kind::Unary:
                return emitUnary(static_cast<const Unary&>(expression));

            case Expr::Kind::Binary:
                return emitBinary(static_cast<const Binary&>(expression));

            case Expr::Kind::Assign: {
                const auto& assign = static_cast<const Assign&>(expression);
                const std::string value = emitExpr(*assign.value);
                line("store i32 " + value + ", ptr " + slotPointer(assign.slot));

                // An assignment's value is the value assigned, which is
                // what makes a = b = 0 work.
                return value;
            }

            case Expr::Kind::Call:
                return emitCall(static_cast<const Call&>(expression));
        }

        return "0";
    }

    // Conditions are i32 in MiniC and i1 in LLVM.
    std::string emitTruth(const Expr& expression) {
        const std::string value = emitExpr(expression);
        const std::string result = freshValue();
        line(result + " = icmp ne i32 " + value + ", 0");
        return result;
    }

    std::string emitUnary(const Unary& unary) {
        const std::string value = emitExpr(*unary.operand);

        if (unary.op == TokenType::Not) {
            const std::string isZero = freshValue();
            const std::string result = freshValue();
            line(isZero + " = icmp eq i32 " + value + ", 0");
            line(result + " = zext i1 " + isZero + " to i32");
            return result;
        }

        // Negating INT_MIN is the one case that overflows.
        trapIf("icmp eq i32 " + value + ", " + INT_MIN_TEXT,
               TrapNegationOverflow, unary.line);

        const std::string result = freshValue();
        line(result + " = sub i32 0, " + value);
        return result;
    }

    std::string emitBinary(const Binary& binary) {
        if (binary.op == TokenType::AndAnd || binary.op == TokenType::OrOr) {
            return emitShortCircuit(binary);
        }

        const std::string lhs = emitExpr(*binary.lhs);
        const std::string rhs = emitExpr(*binary.rhs);

        switch (binary.op) {
            case TokenType::Plus:
                return emitChecked("sadd", lhs, rhs, binary.line);
            case TokenType::Minus:
                return emitChecked("ssub", lhs, rhs, binary.line);
            case TokenType::Star:
                return emitChecked("smul", lhs, rhs, binary.line);

            case TokenType::Slash:
                return emitDivide(lhs, rhs, binary.line);
            case TokenType::Percent:
                return emitRemainder(lhs, rhs, binary.line);

            case TokenType::EqualEqual:
                return emitCompare("eq", lhs, rhs);
            case TokenType::NotEqual:
                return emitCompare("ne", lhs, rhs);
            case TokenType::Less:
                return emitCompare("slt", lhs, rhs);
            case TokenType::LessEqual:
                return emitCompare("sle", lhs, rhs);
            case TokenType::Greater:
                return emitCompare("sgt", lhs, rhs);
            case TokenType::GreaterEqual:
                return emitCompare("sge", lhs, rhs);

            default:
                break;
        }

        return "0";
    }

    std::string emitCompare(const char* predicate, const std::string& lhs,
                            const std::string& rhs) {
        const std::string flag = freshValue();
        const std::string result = freshValue();
        line(flag + " = icmp " + predicate + " i32 " + lhs + ", " + rhs);
        line(result + " = zext i1 " + flag + " to i32");
        return result;
    }

    // The VM computes in 64 bits and rejects anything outside int. The
    // intrinsics report the same condition without widening.
    std::string emitChecked(const char* operation, const std::string& lhs,
                            const std::string& rhs, int sourceLine) {
        const std::string pair = freshValue();
        const std::string value = freshValue();
        const std::string overflow = freshValue();

        line(pair + " = call {i32, i1} @llvm." + operation +
             ".with.overflow.i32(i32 " + lhs + ", i32 " + rhs + ")");
        line(value + " = extractvalue {i32, i1} " + pair + ", 0");
        line(overflow + " = extractvalue {i32, i1} " + pair + ", 1");

        trapOn(overflow, TrapOverflow, sourceLine);

        return value;
    }

    // sdiv is undefined for a zero divisor and for INT_MIN / -1, so both
    // are tested first. The zero test comes first because that is the
    // order the VM reports them in.
    std::string emitDivide(const std::string& lhs, const std::string& rhs,
                           int sourceLine) {
        trapIf("icmp eq i32 " + rhs + ", 0", TrapDivisionByZero, sourceLine);
        trapIf(overflowingDivision(lhs, rhs), TrapDivisionOverflow, sourceLine);

        const std::string result = freshValue();
        line(result + " = sdiv i32 " + lhs + ", " + rhs);
        return result;
    }

    // INT_MIN % -1 is zero in the VM, but it is undefined for srem, so the
    // zero is produced without ever reaching the instruction.
    std::string emitRemainder(const std::string& lhs, const std::string& rhs,
                              int sourceLine) {
        trapIf("icmp eq i32 " + rhs + ", 0", TrapRemainderByZero, sourceLine);

        const std::string special = freshValue();
        line(special + " = " + overflowingDivision(lhs, rhs));

        const std::string zeroLabel = freshLabel("remzero");
        const std::string computeLabel = freshLabel("rem");
        const std::string endLabel = freshLabel("endrem");

        terminate("br i1 " + special + ", label %" + zeroLabel + ", label %" +
                  computeLabel);

        startBlock(zeroLabel);
        terminate("br label %" + endLabel);

        startBlock(computeLabel);
        const std::string computed = freshValue();
        line(computed + " = srem i32 " + lhs + ", " + rhs);
        terminate("br label %" + endLabel);

        startBlock(endLabel);
        const std::string result = freshValue();
        line(result + " = phi i32 [ 0, %" + zeroLabel + " ], [ " + computed +
             ", %" + computeLabel + " ]");
        return result;
    }

    // The condition shared by the two signed-division edge cases.
    std::string overflowingDivision(const std::string& lhs,
                                    const std::string& rhs) {
        const std::string isMin = freshValue();
        const std::string isMinusOne = freshValue();
        line(isMin + " = icmp eq i32 " + lhs + ", " + INT_MIN_TEXT);
        line(isMinusOne + " = icmp eq i32 " + rhs + ", -1");
        return "and i1 " + isMin + ", " + isMinusOne;
    }

    void trapIf(const std::string& condition, Trap kind, int sourceLine) {
        const std::string flag = freshValue();
        line(flag + " = " + condition);
        trapOn(flag, kind, sourceLine);
    }

    // The trap block sits inline rather than being shared across a
    // function: a shared block would need a phi to carry the line number,
    // and the optimizer folds these away anyway.
    void trapOn(const std::string& flag, Trap kind, int sourceLine) {
        const std::string trapLabel = freshLabel("trap");
        const std::string okLabel = freshLabel("ok");

        terminate("br i1 " + flag + ", label %" + trapLabel + ", label %" +
                  okLabel);

        startBlock(trapLabel);
        line("call void @minic_trap(i32 " + std::to_string(static_cast<int>(kind)) +
             ", i32 " + std::to_string(sourceLine) + ")");
        terminate("unreachable");

        startBlock(okLabel);
    }

    // && and || must not evaluate their right side unless the left side
    // leaves the answer open, so each becomes a branch and a phi. The
    // incoming blocks are captured rather than assumed, because either
    // operand may itself have opened new blocks.
    std::string emitShortCircuit(const Binary& binary) {
        const bool isAnd = binary.op == TokenType::AndAnd;
        const std::string rhsLabel = freshLabel(isAnd ? "and.rhs" : "or.rhs");
        const std::string endLabel = freshLabel(isAnd ? "and.end" : "or.end");

        const std::string lhs = emitTruth(*binary.lhs);
        const std::string fromLhs = block_;

        // For &&, a false left side settles it; for ||, a true one does.
        terminate(isAnd ? "br i1 " + lhs + ", label %" + rhsLabel + ", label %" + endLabel
                        : "br i1 " + lhs + ", label %" + endLabel + ", label %" + rhsLabel);

        startBlock(rhsLabel);
        const std::string rhs = emitTruth(*binary.rhs);
        const std::string rhsValue = freshValue();
        line(rhsValue + " = zext i1 " + rhs + " to i32");
        const std::string fromRhs = block_;
        terminate("br label %" + endLabel);

        startBlock(endLabel);
        const std::string result = freshValue();
        const char* shortcut = isAnd ? "0" : "1";
        line(result + " = phi i32 [ " + shortcut + ", %" + fromLhs + " ], [ " +
             rhsValue + ", %" + fromRhs + " ]");

        return result;
    }

    std::string emitCall(const Call& call) {
        std::vector<std::string> arguments;
        arguments.reserve(call.args.size());

        for (const ExprPtr& argument : call.args) {
            arguments.push_back(emitExpr(*argument));
        }

        std::string list;

        for (std::size_t i = 0; i < arguments.size(); ++i) {
            list += (i > 0 ? ", " : "");
            list += "i32 " + arguments[i];
        }

        if (call.resolution == Call::Resolution::Builtin) {
            line("call void @minic_print(" + list + ")");
            return "0";
        }

        const Function& callee =
            program_.functions[static_cast<std::size_t>(call.target)];

        if (callee.returnsVoid) {
            line("call void " + mangle(callee.name) + "(" + list + ")");
            return "0";
        }

        const std::string result = freshValue();
        line(result + " = call i32 " + mangle(callee.name) + "(" + list + ")");
        return result;
    }

    const Program& program_;
    std::ostream& out_;

    std::string block_;
    bool terminated_ = false;
    int nextId_ = 0;
};

}  // namespace

void emitLlvm(const Program& program, std::ostream& out) {
    Emitter(program, out).run();
}
